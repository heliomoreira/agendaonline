            <section>
                <h2 id="identificacao">1. Quem presta o serviço</h2>
                <p class="intro">Estes Termos e Condições regulam a utilização da plataforma Agenda Online, disponível em agendaonline.pt.</p>
                <p>A Agenda Online é explorada por Hélio Jorge da Silva Moreira, empresário em nome individual 235385395, com sede em R. Dr. Mário Cal Brandão, 302 - Águas Santas (adiante "Agenda Online", "nós").</p>
                <p>Pode contactar-nos através de <a href="mailto:agendaonline@bitsis.pt">agendaonline@bitsis.pt</a>.</p>
            </section>

            <section>
                <h2 id="objeto">2. Objeto e aceitação</h2>
                <p>A Agenda Online é um software de gestão de marcações, disponibilizado através da internet, que permite a profissionais e empresas (adiante "Utilizador") receber marcações online dos seus clientes, gerir a sua agenda e fichas de clientes, e enviar confirmações e lembretes por email e SMS.</p>
                <p>Ao criar uma conta ou utilizar a plataforma, o Utilizador declara ter lido e aceitado estes Termos e a <a href="/privacidade/">Política de Privacidade</a>. Se não concordar, não deve utilizar o serviço.</p>
                <p>A plataforma destina-se à utilização no âmbito de uma atividade profissional ou empresarial.</p>
            </section>

            <section>
                <h2 id="beta">3. Versão beta</h2>
                <p>A Agenda Online encontra-se em fase beta. Isto significa que:</p>
                <ul>
                    <li>as funcionalidades podem ser acrescentadas, alteradas ou removidas durante esta fase;</li>
                    <li>podem ocorrer erros, interrupções ou comportamentos inesperados, que procuraremos corrigir com a maior brevidade possível;</li>
                    <li>o Utilizador pode ser convidado a dar feedback, que poderemos usar livremente para melhorar o serviço, sem que daí resulte qualquer obrigação de compensação.</li>
                </ul>
                <p>Recomendamos que o Utilizador exporte regularmente os dados que considere essenciais à sua atividade.</p>
            </section>

            <section>
                <h2 id="conta">4. Conta de utilizador</h2>
                <p>Para utilizar a plataforma é necessário criar uma conta. O Utilizador compromete-se a:</p>
                <ul>
                    <li>ter pelo menos 18 anos e capacidade para contratar em nome próprio ou da entidade que representa;</li>
                    <li>fornecer informações verdadeiras, completas e atualizadas;</li>
                    <li>manter a confidencialidade das suas credenciais de acesso e não as partilhar com terceiros;</li>
                    <li>informar-nos de imediato de qualquer utilização não autorizada da sua conta.</li>
                </ul>
                <p>O Utilizador é responsável por toda a atividade realizada na sua conta, incluindo a dos membros da equipa a quem dê acesso.</p>
            </section>

            <section>
                <h2 id="utilizacao">5. Utilização aceitável</h2>
                <p>O Utilizador compromete-se a utilizar a plataforma de forma lícita e de acordo com estes Termos. Em particular, não pode:</p>
                <ul>
                    <li>enviar comunicações publicitárias não solicitadas (spam) através do sistema de SMS ou email;</li>
                    <li>inserir conteúdos ilícitos, ofensivos, difamatórios ou que violem direitos de terceiros;</li>
                    <li>tentar aceder a contas ou dados de outros utilizadores, ou contornar medidas de segurança;</li>
                    <li>copiar, descompilar, fazer engenharia reversa ou revender a plataforma ou partes dela;</li>
                    <li>utilizar a plataforma de forma que prejudique o seu funcionamento ou sobrecarregue a infraestrutura.</li>
                </ul>
            </section>

            <section>
                <h2 id="comunicacoes">6. Comunicações enviadas aos clientes do Utilizador</h2>
                <p>As confirmações e lembretes enviados por email e SMS são enviados em nome do Utilizador e para os contactos por ele introduzidos ou fornecidos pelos seus clientes no momento da marcação.</p>
                <p>O Utilizador é o único responsável:</p>
                <ul>
                    <li>por dispor de fundamento legal para contactar os seus clientes;</li>
                    <li>pelo conteúdo das mensagens que personalize;</li>
                    <li>pela exatidão dos contactos introduzidos.</li>
                </ul>
                <p>As mensagens enviadas através da plataforma destinam-se a comunicações relacionadas com marcações e não podem ser usadas para fins de marketing sem o consentimento dos destinatários, nos termos da lei aplicável.</p>
            </section>

            <section>
                <h2 id="precos">7. Preços e pagamento</h2>
                <p>A utilização de determinadas funcionalidades está sujeita a pagamento, nomeadamente o envio de SMS, que é cobrado por mensagem enviada.</p>
                <p>Os preços em vigor são os indicados na área de conta do Utilizador no momento da utilização. Aos preços acresce IVA à taxa legal em vigor, quando aplicável.</p>
                <p>Qualquer alteração de preços é comunicada ao Utilizador com, pelo menos, 30 dias de antecedência. Se não concordar com a alteração, o Utilizador pode cancelar a sua conta antes da data em que esta produza efeitos.</p>
                <p>Os montantes pagos não são reembolsáveis, salvo nos casos previstos na lei.</p>
            </section>

            <section>
                <h2 id="dados">8. Proteção de dados pessoais</h2>
                <p>O tratamento dos dados pessoais do Utilizador (dados de conta, faturação e utilização) é feito pela Agenda Online na qualidade de responsável pelo tratamento, conforme descrito na <a href="/privacidade/">Política de Privacidade</a>.</p>
                <p>Quanto aos dados dos clientes do Utilizador inseridos na plataforma (nomes, contactos, marcações, notas), o Utilizador é o responsável pelo tratamento e a Agenda Online atua como subcontratante, nos termos do artigo 28.º do Regulamento Geral sobre a Proteção de Dados (RGPD). Nessa qualidade, a Agenda Online compromete-se a:</p>
                <ul>
                    <li>tratar esses dados apenas para prestar o serviço e de acordo com as instruções documentadas do Utilizador, incluindo as que resultam da configuração da sua conta;</li>
                    <li>garantir que as pessoas autorizadas a tratar os dados estão sujeitas a dever de confidencialidade;</li>
                    <li>aplicar medidas técnicas e organizativas adequadas para proteger os dados;</li>
                    <li>recorrer apenas a subcontratantes ulteriores que ofereçam garantias suficientes, mantendo a lista atualizada na Política de Privacidade e informando o Utilizador de alterações, que poderá opor-se;</li>
                    <li>prestar assistência ao Utilizador na resposta a pedidos de exercício de direitos dos titulares dos dados;</li>
                    <li>notificar o Utilizador, sem demora injustificada, de qualquer violação de dados pessoais de que tome conhecimento;</li>
                    <li>no fim do contrato, apagar ou devolver os dados, nos termos da secção 12;</li>
                    <li>disponibilizar a informação necessária para demonstrar o cumprimento destas obrigações.</li>
                </ul>
                <p>O Utilizador garante que dispõe de fundamento legal para tratar os dados dos seus clientes e que lhes presta a informação exigida pelo RGPD.</p>
            </section>

            <section>
                <h2 id="disponibilidade">9. Disponibilidade e suporte</h2>
                <p>Procuramos manter a plataforma disponível de forma contínua, mas não garantimos que funcione sem interrupções ou erros, em especial durante a fase beta.</p>
                <p>Podemos suspender temporariamente o acesso para manutenção, atualizações ou por razões de segurança, procurando avisar com antecedência sempre que possível.</p>
                <p>O suporte é prestado em português, através de <a href="mailto:agendaonline@bitsis.pt">agendaonline@bitsis.pt</a>, em dias úteis.</p>
            </section>

            <section>
                <h2 id="propriedade">10. Propriedade intelectual</h2>
                <p>A plataforma, incluindo o software, o design, a marca Agenda Online e os conteúdos por nós criados, é propriedade de Hélio Jorge da Silva Moreira ou dos seus licenciantes. Estes Termos concedem ao Utilizador apenas um direito de utilização não exclusivo e intransmissível, enquanto a conta estiver ativa.</p>
                <p>Os dados e conteúdos inseridos pelo Utilizador continuam a ser seus. O Utilizador concede-nos apenas a autorização necessária para os alojar, tratar e apresentar no âmbito da prestação do serviço.</p>
            </section>

            <section>
                <h2 id="responsabilidade">11. Responsabilidade</h2>
                <p>Na máxima medida permitida por lei, a Agenda Online não é responsável por:</p>
                <ul>
                    <li>lucros cessantes, perda de clientes ou de oportunidades de negócio;</li>
                    <li>faltas de clientes a marcações ou falhas na entrega de SMS e emails imputáveis a operadores de telecomunicações ou a dados de contacto incorretos;</li>
                    <li>danos resultantes de utilização indevida da conta ou do incumprimento destes Termos pelo Utilizador.</li>
                </ul>
                <p>Sem prejuízo do disposto acima, a responsabilidade total da Agenda Online fica limitada ao montante pago pelo Utilizador nos 12 meses anteriores ao facto que a origina.</p>
                <p>Nada nestes Termos exclui ou limita a responsabilidade por dolo ou culpa grave, nem qualquer outra responsabilidade que não possa ser excluída nos termos da lei.</p>
            </section>

            <section>
                <h2 id="cessacao">12. Suspensão e cessação</h2>
                <p>O Utilizador pode cancelar a sua conta a qualquer momento, a partir da área de conta ou através de <a href="mailto:agendaonline@bitsis.pt">agendaonline@bitsis.pt</a>.</p>
                <p>Podemos suspender ou encerrar uma conta em caso de incumprimento destes Termos, falta de pagamento ou utilização que coloque em risco a plataforma ou terceiros, avisando previamente o Utilizador sempre que a situação o permita.</p>
                <p>Após o encerramento da conta, o Utilizador dispõe de 30 dias para pedir a exportação dos seus dados. Decorrido esse prazo, os dados são apagados, exceto os que tenhamos de conservar por obrigação legal.</p>
            </section>

            <section>
                <h2 id="alteracoes">13. Alterações aos Termos</h2>
                <p>Podemos alterar estes Termos, nomeadamente para refletir alterações ao serviço ou à lei. As alterações relevantes são comunicadas por email ou na plataforma com, pelo menos, 30 dias de antecedência. A continuação da utilização após essa data significa a aceitação dos novos Termos.</p>
            </section>

