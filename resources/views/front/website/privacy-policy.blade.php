                <h2 id="seguranca">8. Segurança</h2>
                <p>Aplicamos medidas técnicas e organizativas para proteger os dados contra acesso não autorizado, perda ou alteração, incluindo comunicações cifradas (HTTPS), palavras-passe guardadas de forma cifrada, controlo de acessos e cópias de segurança regulares.</p>
                <p>Em caso de violação de dados pessoais que represente um risco, notificaremos a Comissão Nacional de Proteção de Dados e, quando exigido, as pessoas afetadas, nos prazos previstos no RGPD.</p>
            </section>

            <section>
                <h2 id="direitos">9. Os seus direitos</h2>
                <p>Nos termos do RGPD, tem direito a:</p>
                <ul>
                    <li>aceder aos seus dados e obter uma cópia;</li>
                    <li>pedir a retificação de dados incorretos ou incompletos;</li>
                    <li>pedir o apagamento dos seus dados, quando não exista motivo legal para os conservarmos;</li>
                    <li>pedir a limitação do tratamento;</li>
                    <li>opor-se ao tratamento baseado em interesse legítimo e, a qualquer momento, ao marketing;</li>
                    <li>receber os seus dados num formato estruturado e de uso corrente (portabilidade);</li>
                    <li>retirar o consentimento a qualquer momento, sem afetar a licitude do tratamento anterior.</li>
                </ul>
                <p>Para exercer estes direitos, contacte-nos através de <a href="mailto:agendaonline@bitsis.pt">agendaonline@bitsis.pt</a>. Respondemos no prazo de um mês, que pode ser prorrogado nos casos previstos na lei. Poderemos pedir informação adicional para confirmar a sua identidade.</p>
                <p>Tem ainda o direito de apresentar reclamação à Comissão Nacional de Proteção de Dados (CNPD), em <a href="https://www.cnpd.pt" rel="noopener">www.cnpd.pt</a>.</p>
