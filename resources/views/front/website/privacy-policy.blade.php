                <h2 id="conservacao">5. Durante quanto tempo guardamos os dados</h2>
                <ul>
                    <li><strong>Dados de conta e configuração:</strong> enquanto a conta estiver ativa e até 30 dias após o seu encerramento, para permitir a exportação de dados.</li>
                    <li><strong>Dados dos clientes dos utilizadores:</strong> enquanto a conta do utilizador estiver ativa, sendo apagados ou devolvidos no prazo indicado acima.</li>
                    <li><strong>Dados de faturação:</strong> durante 10 anos, conforme exigido pela legislação fiscal portuguesa.</li>
                    <li><strong>Registos técnicos (logs):</strong> até 12 meses.</li>
                    <li><strong>Pedidos de suporte:</strong> até 2 anos após a resolução do pedido.</li>
                    <li><strong>Consentimento para marketing:</strong> até o retirar.</li>
                </ul>
