                <h2 id="quem-somos">1. Quem somos</h2>
                <p class="intro">Esta Política explica que dados pessoais tratamos, para quê, durante quanto tempo e que direitos tem.</p>
                <p>O responsável pelo tratamento dos dados descritos nesta Política é Hélio Jorge da Silva Moreira, empresário em nome individual n.º 235385395, com sede em R. Dr. Mário Cal Brandão 302 - Águas Santas, que explora a plataforma Agenda Online (adiante "nós").</p>
                <p>Para qualquer questão sobre dados pessoais, contacte-nos através de <a href="mailto:agendaonline@bitsis.pt">agendaonline@bitsis.pt</a>.</p>
            </section>

            <section>
                <h2 id="ambito">2. A quem se aplica</h2>
                <p>Esta Política aplica-se a:</p>
                <ul>
                    <li><strong>visitantes</strong> do site agendaonline.pt;</li>
                    <li><strong>utilizadores</strong>, ou seja, os profissionais e empresas que criam conta na Agenda Online, e os membros das suas equipas.</li>
                </ul>
                <h3>Se marcou um serviço através da Agenda Online</h3>
                <p>Quando marca um serviço num negócio que usa a Agenda Online (por exemplo, um salão ou uma clínica), o responsável pelos seus dados é esse negócio. Nós tratamos esses dados apenas por conta dele, como subcontratante, para que a marcação funcione.</p>
                <p>Para exercer os seus direitos, deve contactar diretamente o negócio onde marcou. Se nos contactar, encaminharemos o pedido.</p>
            </section>

            <section>
                <h2 id="dados">3. Que dados tratamos</h2>
                <h3>Dados que nos fornece</h3>
                <ul>
                    <li><strong>Dados de conta:</strong> nome, nome do negócio, email, telefone e palavra-passe (guardada de forma cifrada).</li>
                    <li><strong>Dados de faturação:</strong> nome ou denominação, NIF e morada de faturação.</li>
                    <li><strong>Dados de configuração:</strong> serviços, horários, membros da equipa e outras definições da conta.</li>
                    <li><strong>Comunicações:</strong> o conteúdo dos pedidos de suporte e mensagens que nos envia.</li>
                </ul>
                <h3>Dados recolhidos automaticamente</h3>
                <ul>
                    <li><strong>Dados técnicos:</strong> endereço IP, tipo de browser e dispositivo, datas e horas de acesso e registos de atividade (logs), usados para garantir a segurança e o bom funcionamento da plataforma.</li>
                </ul>
                <h3>Dados dos clientes dos utilizadores</h3>
                <p>Os utilizadores inserem na plataforma dados dos seus próprios clientes, como nome, telefone, email, histórico de marcações e notas. Tratamos esses dados como subcontratantes, apenas por conta e segundo as instruções do utilizador, nos termos dos <a href="/termos/#dados">Termos e Condições</a>.</p>
            </section>

